-- معرض تحكمات متشابهة: صور يرفعها المدير وتظهر للزبائن المسجلين
create table if not exists public.similar_remote_images (
  id bigint generated by default as identity primary key,
  title text not null default '',
  image_url text not null,
  storage_path text not null,
  created_at timestamptz not null default now(),
  created_by uuid references auth.users(id) on delete set null
);

alter table public.similar_remote_images enable row level security;

drop policy if exists "Customers can view similar remote images" on public.similar_remote_images;
create policy "Customers can view similar remote images"
on public.similar_remote_images for select
to authenticated
using (true);

drop policy if exists "Admins can add similar remote images" on public.similar_remote_images;
create policy "Admins can add similar remote images"
on public.similar_remote_images for insert
to authenticated
with check (public.is_admin());

drop policy if exists "Admins can delete similar remote images" on public.similar_remote_images;
create policy "Admins can delete similar remote images"
on public.similar_remote_images for delete
to authenticated
using (public.is_admin());

-- السماح للمدير فقط برفع الصور ضمن مجلد المعرض في bucket الموقع
drop policy if exists "Admins upload similar remote gallery images" on storage.objects;
create policy "Admins upload similar remote gallery images"
on storage.objects for insert
to authenticated
with check (
  bucket_id = 'site-media'
  and (storage.foldername(name))[1] = 'similar-remotes'
  and public.is_admin()
);

drop policy if exists "Admins delete similar remote gallery images" on storage.objects;
create policy "Admins delete similar remote gallery images"
on storage.objects for delete
to authenticated
using (
  bucket_id = 'site-media'
  and (storage.foldername(name))[1] = 'similar-remotes'
  and public.is_admin()
);
